// Fallback for unknown tech: clean badge
function TextBadge({ name }: { name: string }) {
  const abbrev = name.length <= 3 ? name : name.slice(0, 2).toUpperCase();
  return (
    <span
      className="flex h-4 w-4 items-center justify-center rounded-[2px] bg-[--surface-2] font-mono text-[8px] font-bold text-[--foreground]"
      aria-hidden="true"
    >
      {abbrev}
    </span>
  );
}

export function TechIcon({ name, size = 18 }: TechIconProps) {
  const icon = icons[name];
  if (!icon) return <TextBadge name={name} />;

  return (
    <span
      style={{
        width: size,
        height: size,
        display: "inline-flex",
        alignItems: "center",
        justifyContent: "center",
        flexShrink: 0
      }}
      aria-hidden="true"
    >
      {icon}
    </span>
  );
}
